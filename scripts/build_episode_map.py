"""Generate backend/data/ps02_episode_map.yaml once (seed 2026); the output is committed for audit.

Usage: uv run python scripts/build_episode_map.py [--check]
"""

from __future__ import annotations

import csv
import random
import sys
from datetime import datetime, timedelta
from pathlib import Path

import yaml

from sentinel.calendar import events_at
from sentinel.ids import false_alarm_id, ps02_incident_id

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "data" / "ps02_system_telemetry.csv"
OUT = ROOT / "backend" / "data" / "ps02_episode_map.yaml"
SEED = 2026
ABRUPT_SHARE = 0.2
CASCADE = ("2026-08-01T10:38:14", "2026-08-01T10:59:06")
N6_ANCHOR = "2026-08-14T03:18:43"  # no calendar entry covers it
N6_TOTAL = 4
N4_TOTAL = 4

# Closest-shape table for metrics not claimed by a service rule or the named metric rules.
SHAPE_TABLE = {
    "cpu_usage": "RC-QUEUE",  # saturation ramp
    "disk_io": "RC-QUEUE",  # backlog drain pressure
    "latency_p99": "RC-DBPOOL",  # slow dependency ramp
    "error_rate": "RC-DBPOOL",  # errors from a starved dependency
}

HEADER = """\
# PS-02 episode map: one entry per CRITICAL CSV row (50 = 28 incidents + 22 false alarms).
# GENERATED by scripts/build_episode_map.py (seed 2026); do not hand edit. Regenerate and diff.
#
# Rules (docs/SENTINEL_IMPLEMENTATION_PLAN.md, Phase 2 'Episode map rule'):
#  1. Seeded draw marks round(0.2 * 28) = 6 incidents RC-ABRUPT (the cascade pair is excluded).
#  2. Service rules: PaymentGateway -> RC-BANK (connection_pool -> RC-DBPOOL);
#     NotificationHub -> RC-OTP-PROVIDER (connection_pool -> RC-DBPOOL);
#     AuthService error_rate -> RC-AUTH-ATTACK.
#  3. Metric rules: connection_pool -> RC-DBPOOL, queue_depth -> RC-QUEUE,
#     memory_usage -> RC-MEMLEAK.
#  4. Closest-shape table for the rest: cpu_usage -> RC-QUEUE, disk_io -> RC-QUEUE,
#     latency_p99 -> RC-DBPOOL, error_rate -> RC-DBPOOL.
#  RC-CERT is never anchor-mapped (D7). Segments: RC-BANK bank=BANK_x (BANK_C at least once),
#  RC-OTP-PROVIDER provider=P1|P2.
# Negatives: rows inside a calendar.yaml window -> N1 (campaign/salary) or N3 (EOD batch) with the
#  event ids as benign_evidence; N6 (unexplained, no evidence) incl. 2026-08-14T03:18; N4 (deploy
#  blip) cite synthetic deploy events listed under `events:`; the rest N5 (transient).
# D6: the 2026-08-16 SearchAPI (06:20) / UserProfileService (06:32) pair is NOT a cascade; the
#  topology has no edge between them, so they stay two independent incidents.
# D8: the Azadi and cashback calendar entries were authored to explain anchors (disclosed).
# Cascade: INC-0001 AuthService -> INC-0002 PaymentGateway on 2026-08-01 (both RC-DBPOOL).
"""


def _rows() -> list[dict[str, str]]:
    with CSV.open() as f:
        rows = [r for r in csv.DictReader(f) if r["alert_level"] == "CRITICAL"]
    return sorted(rows, key=lambda r: r["timestamp"])


def _incident_code(service: str, metric: str) -> str:
    if service == "PaymentGateway":
        return "RC-DBPOOL" if metric == "connection_pool" else "RC-BANK"
    if service == "NotificationHub":
        return "RC-DBPOOL" if metric == "connection_pool" else "RC-OTP-PROVIDER"
    if service == "AuthService" and metric == "error_rate":
        return "RC-AUTH-ATTACK"
    named = {
        "connection_pool": "RC-DBPOOL",
        "queue_depth": "RC-QUEUE",
        "memory_usage": "RC-MEMLEAK",
    }
    return named.get(metric) or SHAPE_TABLE[metric]


def build() -> str:
    rng = random.Random(SEED)
    rows = _rows()
    inc_rows = [r for r in rows if r["is_incident"] == "1"]
    fa_rows = [r for r in rows if r["is_incident"] != "1"]
    assert len(inc_rows) == 28 and len(fa_rows) == 22

    eligible = [r["timestamp"] for r in inc_rows if r["timestamp"] not in CASCADE]
    abrupt = set(rng.sample(eligible, round(ABRUPT_SHARE * len(inc_rows))))

    entries: list[dict] = []
    bank_seen: list[dict] = []
    ids = {}
    for n, r in enumerate(inc_rows, 1):
        ts = r["timestamp"]
        ids[ts] = ps02_incident_id(n)
        is_abrupt = ts in abrupt
        base = _incident_code(r["service_name"], r["metric_type"])
        code = "RC-ABRUPT" if is_abrupt else base
        seg = "*"
        if code == "RC-BANK":
            seg = f"bank={rng.choice(['BANK_A', 'BANK_B', 'BANK_C'])}"
        elif code == "RC-OTP-PROVIDER":
            seg = f"provider={rng.choice(['P1', 'P2'])}"
        e = _entry(r, "incident", code, ids[ts], is_abrupt, seg)
        e["rationale"] = (
            f"seeded 20% abrupt draw (rule base {base})"
            if is_abrupt
            else f"{r['service_name']} {r['metric_type']} -> {code}"
        )
        if code == "RC-BANK":
            bank_seen.append(e)
        entries.append(e)
    if not any(e["segment_key"] == "bank=BANK_C" for e in bank_seen):
        bank_seen[0]["segment_key"] = "bank=BANK_C"
    for e in entries:
        if e["anchor_ts"] == CASCADE[1]:
            e["cascade_parent"] = ids[CASCADE[0]]
            e["rationale"] += "; cascade from INC-0001 (AuthService DB pool exhaustion)"

    # False alarms: calendar first, then seeded N6/N4/N5 assignment of the remainder.
    deploys: list[dict] = []
    rest: list[dict[str, str]] = []
    fa_entries: dict[str, dict] = {}
    for n, r in enumerate(fa_rows, 1):
        fid = false_alarm_id(n)
        cal = (
            [] if r["timestamp"] == N6_ANCHOR else events_at(datetime.fromisoformat(r["timestamp"]))
        )
        if cal:
            kinds = {c.kind for c in cal}
            code = "N3" if "eod_settlement" in kinds else "N2" if kinds == {"maintenance"} else "N1"
            e = _entry(r, "negative", code, fid, False, "*")
            e["benign_evidence"] = [c.id for c in cal]
            e["rationale"] = "inside calendar window: " + ", ".join(c.id for c in cal)
            fa_entries[r["timestamp"]] = e
        else:
            rest.append({**r, "_fid": fid})
    pool = [r for r in rest if r["timestamp"] != N6_ANCHOR]
    rng.shuffle(pool)
    n6 = {N6_ANCHOR, *(r["timestamp"] for r in pool[: N6_TOTAL - 1])}
    n4 = {r["timestamp"] for r in pool[N6_TOTAL - 1 : N6_TOTAL - 1 + N4_TOTAL]}
    for r in rest:
        ts, fid = r["timestamp"], r["_fid"]
        if ts in n6:
            e = _entry(r, "negative", "N6", fid, False, "*")
            e["rationale"] = "unexplained: no calendar, deploy or maintenance evidence"
        elif ts in n4:
            ev = f"deploy_{fid}"
            minute = datetime.fromisoformat(ts).replace(second=0)
            deploys.append(
                {
                    "event_id": ev,
                    "ts": (minute - timedelta(minutes=rng.randint(4, 12))).isoformat(),
                    "kind": "deploy",
                    "service": r["service_name"],
                    "text": f"Rolling deploy of {r['service_name']} (synthetic, {ev})",
                }
            )
            e = _entry(r, "negative", "N4", fid, False, "*")
            e["benign_evidence"] = [ev]
            e["rationale"] = "deploy blip shortly before the breach"
        else:
            e = _entry(r, "negative", "N5", fid, False, "*")
            e["rationale"] = "transient spike, self-resolved"
        fa_entries[ts] = e
    entries.extend(fa_entries.values())
    entries.sort(key=lambda e: (e["kind"] != "incident", e["episode_id"]))
    deploys.sort(key=lambda d: d["ts"])

    doc = {"seed": SEED, "episodes": entries, "events": deploys}
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100)


def _entry(r: dict[str, str], kind: str, code: str, eid: str, abrupt: bool, seg: str) -> dict:
    return {
        "episode_id": eid,
        "anchor_ts": r["timestamp"],
        "service": r["service_name"],
        "metric": r["metric_type"],
        "kind": kind,
        "code": code,
        "onset_ts": datetime.fromisoformat(r["timestamp"]).replace(second=0).isoformat(),
        "abrupt": abrupt,
        "segment_key": seg,
        "cascade_parent": None,
        "benign_evidence": [],
        "rationale": "",
    }


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
