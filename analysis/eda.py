"""Standalone EDA for the PS-02 telemetry CSV. Does not import sentinel.

Writes analysis/outputs/rule_baselines.csv and docs/DATA_DESCRIPTION.md.
"""

import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "ps02_system_telemetry.csv"
OUT_CSV = ROOT / "analysis" / "outputs" / "rule_baselines.csv"
OUT_DOC = ROOT / "docs" / "DATA_DESCRIPTION.md"
SPLIT = "2026-08-21"


def load(path: Path = CSV_PATH) -> list[dict]:
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["value"] = float(r["value"])
        r["threshold"] = float(r["threshold"])
        r["is_incident"] = int(r["is_incident"])
    return rows


def b0(r: dict) -> bool:
    return r["value"] >= r["threshold"]


def b1(r: dict) -> bool:
    return r["alert_level"] == "CRITICAL"


def score(rows: list[dict], rule) -> dict:
    tp = sum(1 for r in rows if rule(r) and r["is_incident"])
    fp = sum(1 for r in rows if rule(r) and not r["is_incident"])
    fn = sum(1 for r in rows if not rule(r) and r["is_incident"])
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": round(precision, 2),
        "recall": round(recall, 2),
    }


def baselines(rows: list[dict]) -> list[dict]:
    test = [r for r in rows if r["timestamp"] >= SPLIT]
    out = []
    for name, rule in (("B0", b0), ("B1", b1)):
        out.append({"config": name, **score(rows, rule)})
        out.append({"config": f"{name}_test_split", **score(test, rule)})
    return out


def table(counter: Counter, head: str) -> str:
    lines = [f"| {head} | rows |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(counter.items())]
    return "\n".join(lines)


def find(rows: list[dict], ts_prefix: str, service: str, metric: str) -> dict:
    return next(
        r
        for r in rows
        if r["timestamp"].startswith(ts_prefix)
        and r["service_name"] == service
        and r["metric_type"] == metric
    )


def verify_calendar(rows: list[dict]) -> None:
    a = find(rows, "2026-08-01T10:38", "AuthService", "connection_pool")
    p = find(rows, "2026-08-01T10:59", "PaymentGateway", "connection_pool")
    assert a["is_incident"] and p["is_incident"]
    fc = {
        (r["timestamp"][:16], r["service_name"], r["metric_type"])
        for r in rows
        if r["alert_level"] == "CRITICAL" and not r["is_incident"]
    }
    for key in (
        ("2026-08-14T03:18", "AnalyticsDashboard", "disk_io"),
        ("2026-08-14T19:49", "AuthService", "memory_usage"),
        ("2026-08-22T20:25", "PaymentGateway", "connection_pool"),
    ):
        assert key in fc, key
    assert not any(k[0] < "2026-08-04" for k in fc)


def write_doc(rows: list[dict], base: list[dict]) -> None:
    inc = [r for r in rows if r["is_incident"]]
    crit = [r for r in rows if r["alert_level"] == "CRITICAL"]
    false_crit = [r for r in crit if not r["is_incident"]]
    test = [r for r in rows if r["timestamp"] >= SPLIT]
    test_inc = sum(r["is_incident"] for r in test)
    test_fc = sum(1 for r in test if r["alert_level"] == "CRITICAL" and not r["is_incident"])
    bl = "\n".join(
        f"| {b['config']} | {b['tp']} | {b['fp']} | {b['fn']} | {b['precision']} | {b['recall']} |"
        for b in base
    )
    doc = f"""# PS-02 Data Description

Generated by `analysis/eda.py` from `data/ps02_system_telemetry.csv`. Do not edit by hand.

## Columns

`timestamp` (ISO, seconds), `service_name`, `metric_type`, `value`, `threshold`,
`alert_level` (NORMAL / WARNING / CRITICAL), `user_count_active`, `error_count_last_hour`,
`response_time_ms`, `is_incident` (0/1 ground truth).

## Counts

- Rows: {len(rows)} (2026-08-01 to 2026-08-30)
- Incidents (`is_incident=1`): {len(inc)}
- CRITICAL rows: {len(crit)} ({len(crit) - len(false_crit)} incident + {len(false_crit)} false)
- Rows with value >= threshold: {sum(b0(r) for r in rows)}

### By alert_level

{table(Counter(r["alert_level"] for r in rows), "alert_level")}

### By service

{table(Counter(r["service_name"] for r in rows), "service")}

### By metric

{table(Counter(r["metric_type"] for r in rows), "metric")}

### Incident rows by metric

{table(Counter(r["metric_type"] for r in inc), "metric")}

## Splits

- Train: timestamps < {SPLIT}; test: timestamps >= {SPLIT} ({len(test)} rows,
  {test_inc} incidents, {test_fc} false CRITICALs).

## Rule baselines

B0 alerts iff value >= threshold; B1 alerts iff alert_level == CRITICAL.

| config | tp | fp | fn | precision | recall |
|---|---|---|---|---|---|
{bl}

## Calendar facts (verified from the CSV)

- 08-01 AuthService connection_pool at 10:38, then PaymentGateway connection_pool at 10:59
  (21 min later): the hero cascade.
- False CRITICALs on 08-14: 03:18 AnalyticsDashboard disk_io and 19:49 AuthService memory_usage.
- False CRITICAL on 08-22 20:25 PaymentGateway connection_pool (test split).
- No false CRITICAL on Aug 1-3.
"""
    OUT_DOC.write_text(doc)


def main() -> None:
    rows = load()
    verify_calendar(rows)
    base = baselines(rows)
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["config", "tp", "fp", "fn", "precision", "recall"])
        w.writeheader()
        w.writerows(base)
    write_doc(rows, base)
    for b in base:
        print(b)


if __name__ == "__main__":
    main()
